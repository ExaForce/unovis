export type MajorRecord = {
  major: string;
  category: string;
  graduates: number;
  medianSalary: number;
}

/** The six largest categories of majors, ordered by their median salary. They're the rows of the chart, bottom to top */
export const categories = [
  'Education',
  'Humanities & Liberal Arts',
  'Health',
  'Biology & Life Science',
  'Business',
  'Engineering',
]

export const categoryColor = (d: MajorRecord): string => `var(--vis-color${categories.indexOf(d.category)})`

export const formatSalary = (salary: number | Date): string => `$${+salary / 1000}K`

export function tooltip (d: MajorRecord): string {
  return `<b>${d.major}</b><br/>${d.category}<br/>Median salary: ${formatSalary(d.medianSalary)}<br/>Graduates: ${d.graduates.toLocaleString()}`
}

